const translations = { uk, en };

export function translate(
  language: Language,
  key: TranslationKey,
  params: Record<string, string | number> = {},
): string {
  return translations[language][key].replace(/\{(\w+)\}/g, (_, name: string) =>
    String(params[name] ?? `{${name}}`),
  );
}

export function importErrorTranslationKey(code: ImportErrorCode): TranslationKey {
  const keys: Record<ImportErrorCode, TranslationKey> = {
    invalidJson: 'importInvalidJson',
    invalidFormat: 'importInvalidFormat',
    unsupportedVersion: 'importUnsupportedVersion',
    tooLarge: 'importTooLarge',
    invalidArchive: 'importInvalidArchive',
    unsafeArchive: 'importUnsafeArchive',
  };
  return keys[code];
}
