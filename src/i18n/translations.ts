const translations = { uk, en };

export function translate(
  language: Language,
  key: TranslationKey,
  params: Record<string, string | number> = {},
): string {
  return translations[language][key].replace(/\{(\w+)\}/g, (_, name: string) =>
    String(params[name] ?? `{${name}}`),
  );
}

export function importErrorTranslationKey(
  code: 'invalidJson' | 'invalidFormat' | 'unsupportedVersion' | 'tooLarge',
): TranslationKey {
  return {
    invalidJson: 'importInvalidJson',
    invalidFormat: 'importInvalidFormat',
    unsupportedVersion: 'importUnsupportedVersion',
    tooLarge: 'importTooLarge',
  }[code] as TranslationKey;
}
